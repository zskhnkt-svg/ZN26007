/* -----------------------------------------------------------------------
 * 1. В начало main.c (после секции USER CODE BEGIN Includes)
 * ----------------------------------------------------------------------- */
#include "sht3x.h"
#include "ble_sensor_service.h"

/* -----------------------------------------------------------------------
 * 2. В функцию main(), секция USER CODE BEGIN 2
 *    (после MX_I2C3_Init() и инициализации BLE)
 * ----------------------------------------------------------------------- */
void patch_main_begin2(void)
{
    /* Инициализация датчика */
    if (SHT3x_Init() != SHT3X_OK) {
        /* Ошибка инициализации — моргаем LED быстро */
        while (1) {
            HAL_GPIO_TogglePin(LED_GPIO_Port, LED_Pin);
            HAL_Delay(100);
        }
    }

    /* Регистрация BLE сервиса — вызывается ПОСЛЕ APP_BLE_Init()! */
    /* BleSensorService_Init() вызывается из svc_ctl.c (см. ниже) */
}

/* -----------------------------------------------------------------------
 * 3. В главный цикл while(1), секция USER CODE BEGIN 3
 * ----------------------------------------------------------------------- */
void patch_main_loop(void)
{
    BleSensorService_Process();   /* опрос датчика + BLE notify */
}
